const LABELS={concept:'基础概念',calc:'分步计算',truth:'真值表分析',fault:'故障定位',design:'项目综合设计'};

function byId(id){return Q.find(q=>q.id===id)||null;}
function normalize(v){
 if(typeof v==='number')return v;
 const s=String(v==null?'':v).trim().replace(/[，,]/g,'').replace(/[^\d.+-]/g,'');
 if(s==='')return NaN;
 return Number(s);
}
/* 判分：返回 {gradable, correct, expected, explain}。
 * 选择题按选项下标；计算题按数值与容差；设计题不判分。 */
function grade(id,input){
 const q=byId(id);
 if(!q)throw new Error('题目不存在：'+id);
 if(q.type==='design')return {gradable:false,correct:null,explain:q.explain};
 if(q.type==='calc'){
  const v=normalize(input);
  const ok=Number.isFinite(v)&&Math.abs(v-q.answer)<=q.tolerance;
  return {gradable:true,correct:ok,expected:q.answer,unit:q.unit||'',
   explain:(ok?'':'正确答案：'+q.answer+(q.unit||'')+'。')+q.explain};
 }
 const idx=Number(input);
 if(!Number.isInteger(idx)||idx<0||idx>=q.options.length){
  return {gradable:true,correct:false,expected:q.answer,explain:'请选择一个选项。'};
 }
 const ok=idx===q.answer;
 return {gradable:true,correct:ok,expected:q.answer,
  explain:(ok?'回答正确。':(q.feedback[idx]||''))+q.explain};
}

